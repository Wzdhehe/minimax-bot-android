"""Copy original MIT mbot skins and port its exact SVG mark to Flutter paths.

No tracing, recoloring or image synthesis. Run --check to detect asset drift.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

APP = Path(__file__).resolve().parent.parent
VENDOR = APP.parent / 'runtime/vendor/minimax-bot'


def products():
    source = (VENDOR / 'miniapp/client/octopus.js').read_text(encoding='utf-8')
    outline = re.search(r"export const OCTOPUS_PATH =\s*'([^']+)';", source)[1]
    tokens = re.findall(r'[MLCHVZ]|-?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?', outline)
    if ''.join(tokens) != re.sub(r'[\s,]+', '', outline):
        raise ValueError('Unsupported upstream SVG path command')
    commands, current, x, y = [], None, 0, 0
    while tokens:
        if tokens[0] in 'MLCHVZ':
            current = tokens.pop(0)
        if current == 'Z':
            commands.append('  ..close()')
            current = None
            continue
        length = {'M': 2, 'L': 2, 'C': 6, 'V': 1, 'H': 1}[current]
        values, tokens = tokens[:length], tokens[length:]
        if len(values) != length or any(value in 'MLCHVZ' for value in values):
            raise ValueError('Unexpected upstream SVG path')
        if current == 'V':
            y = values[0]
            commands.append(f'  ..lineTo({x}, {y})')
        elif current == 'H':
            x = values[0]
            commands.append(f'  ..lineTo({x}, {y})')
        else:
            x, y = values[-2:]
            name = {'M': 'moveTo', 'L': 'lineTo', 'C': 'cubicTo'}[current]
            commands.append(f'  ..{name}({", ".join(values)})')
            if current == 'M':
                current = 'L'
    palettes = re.findall(r"(\w+): \{ stops: \['(#[0-9A-F]+)', '(#[0-9A-F]+)', '(#[0-9A-F]+)'\]", source)
    if len(palettes) != 12:
        raise ValueError('Unexpected upstream palette inventory')
    lines = ['// SPDX-License-Identifier: AGPL-3.0-only', '// GENERATED by tool/sync_mbot_artwork.py; do not edit.',
             '// Original MiniMax Bot artwork: Copyright (c) 2026 MiniMax, MIT.',
             '// Exact silhouette/palettes from runtime/vendor/minimax-bot/miniapp/client/octopus.js.',
             '// Original permission notice is bundled at assets/mbot/LICENSE.minimax-bot.',
             "part of 'bot_avatar.dart';", '', 'final Path _mbotOctopusPath = Path()', *commands]
    lines[-1] += ';'
    lines += ['', 'const _mbotPalettes = <String, List<Color>>{']
    for name, *colors in palettes:
        lines.append(f"  '{name}': [{', '.join('Color(0xff' + color[1:] + ')' for color in colors)}],")
    lines += ['};', '']
    output = {APP / 'lib/bot/bot_avatar_art.dart': '\n'.join(lines).encode()}
    skins = sorted((VENDOR / 'miniapp/client/skins').glob('*.png'))
    if len(skins) != 11:
        raise ValueError('Unexpected upstream material skin inventory')
    for skin in skins:
        output[APP / 'assets/mbot/skins' / skin.name] = skin.read_bytes()
    output[APP / 'assets/mbot/LICENSE.minimax-bot'] = (VENDOR / 'LICENSE').read_text(encoding='utf-8').encode()
    output[APP / 'assets/mbot/ARTWORK-SOURCES.json'] = (json.dumps({
        '_license': 'SPDX-License-Identifier: AGPL-3.0-only; original artwork retains MIT',
        'source': 'dsh-go/runtime/vendor/minimax-bot',
        'octopusSha256': hashlib.sha256(source.encode()).hexdigest(),
        'skins': {path.name: hashlib.sha256(path.read_bytes()).hexdigest() for path in skins},
    }, indent=2) + '\n').encode()
    return output


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in products().items():
        if args.check:
            # Git may check text out as CRLF on Windows. Only text line endings
            # are normalized; PNG assets must remain byte-for-byte identical.
            actual = None if not path.is_file() else (
                path.read_bytes() if path.suffix == '.png' else path.read_text(encoding='utf-8').encode()
            )
            if actual != content:
                parser.exit(1, f'Artwork is missing or stale: {path.relative_to(APP)}\n')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print('Verified original mbot silhouette, 12 palettes, 11 unchanged skins and MIT notice' if args.check else 'Synced original mbot artwork')
